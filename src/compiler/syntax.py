from datatypes import OrderedSet
from utils import *

import os
import re



class Grammar:
    WARNINGS = {
        "dependency" : [],
        "main"       : []
    }
    

    def __init__(self):
        cfg = get_config()

        cfg["formatting"]["indentation"] = False
        cfg["formatting"]["newlines"] = False
        self.main = cfg["paths"]["language"]

        set_config(cfg)


        self.modules = {}
        self.dependencies = self.traverse_dependencies(self.main, main=True)

        for module, lines in self.modules.items():
            self.modules[module] = Module("MAIN" if module == self.main else module, lines)

        print_warnings("syntax not found", self.WARNINGS)


    def traverse_dependencies(self, path: str, main: bool = False) -> OrderedSet:
        """Recursively search for `#require`s from a top-level path, preserving order and building grammar modules during traversal.
        Searches for implementation-specific syntax.txt files; falls back to base directory if not found."""

        implementation = get_config("implementation")
        syntax = f"{path}/{implementation}/syntax.txt"
        if not os.path.exists(syntax):
            syntax = f"{path}/syntax.txt"

            if main and os.path.exists(syntax):
                print_warnings(
                    msg=f"using default syntax",
                    log={"may not be implementation-specific" : [path]}
                )


        dependencies = OrderedSet()

        if os.path.exists(syntax):

            with open(syntax) as file:
                lines = preprocess_text(file)
                
                basic_requirements = [
                    line.removeprefix("#require").strip().replace(".", "/")
                    for line in lines if line.startswith("#require")
                ]

                requirements = OrderedSet()

                while basic_requirements:
                    requirement = basic_requirements.pop(0)

                    # import all modules in folder if specified by ._ suffix
                    if requirement.endswith("/_"):
                        requirement = requirement.strip("/_")
                        submodule = lib(requirement)

                        for subfile in os.listdir(submodule):
                            
                            subfilename = "/".join((submodule, subfile))

                            if os.path.isdir(subfilename) and not any(subfilename.endswith(s) for s in ("interpreter", "compiler")):
                                basic_requirements.append("/".join((requirement, subfile, "_")))
                                requirements.add(subfilename)

                    # also import all antecedent modules
                    else:
                        if "/" in requirement: 
                            # sequentially import antecedent modules, e.g. math, math/infix, math/infix/extended
                            requirements.extend(lib(requirement[:match.start()]) for match in re.finditer("/", requirement))

                        # and of course add the current requirement as well
                        requirements.add(lib(requirement))

                self.modules[path] = filter(lambda x: not x.startswith("#require"), lines)

                dependencies.extend(requirements)

                for requirement in requirements:
                    dependencies.extend(self.traverse_dependencies(requirement))

        else: self.WARNINGS["main" if main else "dependency"].append(path)

        return dependencies

    
    def __str__(self) -> str:
        return "\n\n\n".join(module._str() for module in self.modules.values())
    

    def compile(self) -> str:
        text = f"""'''!!! THIS FILE IS AUTOMATICALLY GENERATED - PLEASE DO NOT MODIFY !!!'''

        

from datatypes import *
from utils import *



##### ABSTRACT SYNTAX TREE #####


        {"".join(module.compile() for module in self.modules.values())}

##### GRAMMAR #####



_MODULES = {self.embed()}

_GRAMMAR = {{ START : {{ ProductionData(START, "MAIN", 0, [PROGRAM]) }} }}

for module, grammar in _MODULES.items():
    for rule, alternatives in grammar.items():
        if not rule in _GRAMMAR: _GRAMMAR[rule] = set()
        
        for variant, pattern in enumerate(alternatives):
            _GRAMMAR[rule].add(ProductionData(rule, module, variant, pattern))



##### ADDENDA #####



_TOKENS = {{
    token 
            for options in _GRAMMAR.values()
        for metadata in options
    for token in metadata.pattern
}}

_TERMINALS = set(filter(lambda x: isinstance(x, str), _TOKENS))
"""
        
        return text
    
    
    def embed(self) -> str:
        return "{\n\n" + ",\n\n".join(module.embed() for module in self.modules.values()) + "\n\n}"



class Module:
    def __init__(self, name: str, lines: list, sep: str = "::="):
        self.name = "MAIN" if name == get_config("language") else name.removeprefix(".lib/").upper().replace("/", "_")
        self.lines = lines
        self.rules = OrderedSet()
        self.indent = 7

        for line in lines:
            self.add_rule(*line.split(sep))
            self.indent = max(self.indent, line.index(sep)-len(sep))


    def add_rule(self, rule: str, regex: str) -> None:
        self.rules.add(Production(self, rule, regex))


    def _str(self) -> str:
        return f"{self.name}\n\n" + "\n".join(production._str(self.indent) for production in self.rules)


    def compile(self) -> str:
        text = f"""
### MODULE : {self.name} ###

{"".join(production.compile() for production in self.rules)}
"""
        
        return text


    def embed(self) -> str:
        return f"'{self.name}' : {{\n" + (
            ",\n".join("   " + production.embed(self.indent) for production in self.rules) if self.rules 
            else "#  No rules found"
        ) + "\n   }"
    


class Production:
    sep = re.compile(r"[^\\]\|")

    
    def __init__(self, module: Module, rule: str, alternatives: str):
        self.module = module

        alternatives = self.sep.split(alternatives)
        variants = len(alternatives)
        
        self.rule, self.alternatives = Nonterminal(rule.strip()), [Pattern(module, rule, pattern, variants) for pattern in alternatives]


    def _str(self, indent: int) -> str:
        return f"{self.rule} {" " * (indent-len(self.rule))} ::= {f"\n{" " * (indent + 5)} | ".join(pattern._str() for pattern in self.alternatives)}"


    def compile(self) -> str:
        text = f"""
class {self.rule.name}(Rule):
   r'''```
{self.rule} ::= {f"\n{" " * (len(self.rule) + 5)}| ".join(pattern.compile() for pattern in self.alternatives)}
    ```'''
"""
        
        return text


    def embed(self, indent: int) -> str:
        return f"{self.rule.name} {" " * (indent-len(self.rule.name))} : [{f", ".join(pattern.embed() for pattern in self.alternatives)}]"



class Pattern:
    regex = re.compile(r"\<[A-Z0-9_]+\>")


    def __init__(self, module: Module, rule: str, pattern: str, variants: int = 1):
        self.module = module
        self.pattern = []
        self.rule = Nonterminal(rule)

        while pattern:
            match = self.regex.search(pattern)

            if match:
                nonterminal = match.group()
                terminal, pattern = map(lambda s: s.strip(), pattern.split(nonterminal, 1))

                if nonterminal in ("<INDENT>", "<DEDENT>") and not get_config("formatting", "indentation"):
                    
                    self.module.add_rule("<INDENT>", get_config("formatting", "indent"))
                    self.module.add_rule("<DEDENT>", get_config("formatting", "dedent"))
                    
                    cfg = get_config()
                    cfg["formatting"]["indentation"] = True
                    set_config(cfg)

                if terminal:
                    
                    if (r"\n" in terminal) and not get_config("formatting", "newlines"):
                        cfg = get_config()
                        cfg["formatting"]["newlines"] = True
                        set_config(cfg)

                    self.pattern.extend(Terminal(token) for token in terminal.split())
                
                self.pattern.append(Nonterminal(nonterminal))

            else:
                pattern = pattern.strip()
                if pattern:
                    self.pattern.extend(Terminal(token) for token in pattern.split())
                    pattern = None


    def _str(self) -> str:
        return " ".join(str(token) for token in self.pattern)
    

    def compile(self) -> str:
        return self._str()


    def embed(self) -> str:
        return "[" + ", ".join(token.embed() for token in self.pattern) + "]"
    


class Nonterminal:
    def __init__(self, nonterminal: str):
        self.name = nonterminal.strip().upper().removeprefix("<").removesuffix(">")
        

    def __repr__(self):
        return f"<{self.name}>"
    

    def __len__(self) -> int:
        return len(self.name)
    

    def embed(self) -> str:
        return self.name



class Terminal:
    def __init__(self, name: str):
        self.regex = name


    def __str__(self):
        return self.regex
    

    def __repr__(self):
        return f"T[{self}]"
    

    def embed(self) -> str:
        return "EPSILON" if self.regex == "ε" else f"r'{self.regex}'"
